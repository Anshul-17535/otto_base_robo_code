#!/usr/bin/env python3
"""Precompress the web UI pages into a gzip PROGMEM blob.

The ESP32 SoftAP is slow, so shipping the ~120 KB HTML page uncompressed makes
the first load take several seconds. Browsers understand `Content-Encoding:
gzip`, so we gzip the pages at build time (not on the MCU) and the firmware just
streams the compressed bytes. Typical result: ~120 KB -> ~22 KB.

WORKFLOW: whenever you edit html_page.h or motion_page.h, re-run this script:

    python3 tools/gen_web_gz.py

It regenerates web_gz.h, which the sketch includes and serves.
"""
import gzip
import re
import pathlib

HERE = pathlib.Path(__file__).resolve().parent.parent  # Otto_ESP32S3/

# (source file, raw-string delimiter, C var name)
PAGES = [
    ("html_page.h",   "rawhtml",    "HTML_PAGE"),
    ("motion_page.h", "motionhtml", "MOTION_PAGE"),
]


def extract(path: pathlib.Path, delim: str) -> bytes:
    text = path.read_text(encoding="utf-8")
    m = re.search(r'R"' + re.escape(delim) + r'\((.*)\)' + re.escape(delim) + r'"',
                  text, re.DOTALL)
    if not m:
        raise SystemExit(f"Could not find R\"{delim}(...)\" block in {path.name}")
    return m.group(1).encode("utf-8")


def emit_array(name: str, data: bytes) -> str:
    gz = gzip.compress(data, compresslevel=9)
    lines = [f"// {name}: {len(data)} B raw -> {len(gz)} B gzip "
             f"({100 * len(gz) // max(1, len(data))}%)"]
    lines.append(f"const unsigned int {name}_GZ_LEN = {len(gz)};")
    lines.append(f"const unsigned char {name}_GZ[] PROGMEM = {{")
    for i in range(0, len(gz), 16):
        chunk = gz[i:i + 16]
        lines.append("  " + ",".join(f"0x{b:02x}" for b in chunk) + ",")
    lines.append("};")
    return "\n".join(lines)


def main() -> None:
    out = [
        "// AUTO-GENERATED by tools/gen_web_gz.py — DO NOT EDIT BY HAND.",
        "// Edit html_page.h / motion_page.h, then re-run the generator.",
        "#pragma once",
        "#include <pgmspace.h>",
        "",
    ]
    for fname, delim, var in PAGES:
        data = extract(HERE / fname, delim)
        out.append(emit_array(var, data))
        out.append("")
        print(f"{fname}: {len(data)} B -> gzip")
    (HERE / "web_gz.h").write_text("\n".join(out), encoding="utf-8")
    print("Wrote web_gz.h")


if __name__ == "__main__":
    main()
